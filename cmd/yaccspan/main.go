// Command yaccspan adds reduction spans to the pinned goyacc v0.52.0 skeleton.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// Fail closed on skeleton changes rather than silently patching the wrong code.
const reduction = `	/* reduction by production yyn */
	if yyDebug >= 2 {
		__yyfmt__.Printf("reduce %v in:\n\t%v\n", yyn, yyStatname(yystate))
	}

	yynt := yyn
	yypt := yyp
	_ = yypt // guard against "declared and not used"

	yyp -= int(yyR2[yyn])
	// yyp is now the index of $0. Perform the default action. Iff the
	// reduced production is ε, $1 is possibly out of range.
	if yyp+1 >= len(yyS) {
		nyys := make([]yySymType, len(yyS)*2)
		copy(nyys, yyS)
		yyS = nyys
	}
	yyVAL = yyS[yyp+1]

	/* consult goto table to find next state */
	yyn = int(yyR1[yyn])
	yyg := int(yyPgo[yyn])
	yyj := yyg + yyS[yyp].yys + 1

	if yyj >= yyLast {
		yystate = int(yyAct[yyg])
	} else {
		yystate = int(yyAct[yyj])
		if int(yyChk[yystate]) != -yyn {
			yystate = int(yyAct[yyg])
		}
	}
	// dummy call; replaced with literal code
	switch yynt {
`

const spanPatch = `	// parserkit/yaccspan: begin
	yyVAL.span = %[1]s.InvalidSpan()
	for yyi := yyp + 1; yyi <= yypt; yyi++ {
		yyVAL.span = %[1]s.Cover(yyVAL.span, yyS[yyi].span)
	}
	// parserkit/yaccspan: end
`

func rewrite(input []byte) ([]byte, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "parser.go", input, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse generated Go: %w", err)
	}
	if !ast.IsGenerated(f) || !bytes.HasPrefix(input, []byte("// Code generated by goyacc ")) {
		return nil, fmt.Errorf("expected a goyacc-generated file")
	}
	var qualifier string
	for _, imp := range f.Imports {
		path, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			return nil, fmt.Errorf("decode import: %w", err)
		}
		if path == "github.com/mia0x75/parserkit/loc" {
			qualifier = "loc"
			if imp.Name != nil {
				qualifier = imp.Name.Name
			}
		}
	}
	if qualifier == "" || qualifier == "." || qualifier == "_" {
		return nil, fmt.Errorf("expected a named parserkit/loc import")
	}
	var hasSpan bool
	var parse *ast.FuncDecl
	for _, decl := range f.Decls {
		switch decl := decl.(type) {
		case *ast.GenDecl:
			for _, spec := range decl.Specs {
				typ, ok := spec.(*ast.TypeSpec)
				if !ok || typ.Name.Name != "yySymType" || typ.Assign.IsValid() {
					continue
				}
				st, ok := typ.Type.(*ast.StructType)
				if !ok {
					continue
				}
				for _, field := range st.Fields.List {
					if len(field.Names) != 1 || field.Names[0].Name != "span" {
						continue
					}
					sel, ok := field.Type.(*ast.SelectorExpr)
					if !ok {
						continue
					}
					pkg, ok := sel.X.(*ast.Ident)
					hasSpan = ok && pkg.Name == qualifier && sel.Sel.Name == "Span"
				}
			}
		case *ast.FuncDecl:
			if decl.Name.Name != "Parse" || decl.Recv == nil || len(decl.Recv.List) != 1 {
				continue
			}
			ptr, ok := decl.Recv.List[0].Type.(*ast.StarExpr)
			if !ok {
				continue
			}
			recv, ok := ptr.X.(*ast.Ident)
			if ok && recv.Name == "yyParserImpl" {
				if parse != nil {
					return nil, fmt.Errorf("duplicate yyParserImpl.Parse")
				}
				parse = decl
			}
		}
	}
	if !hasSpan || parse == nil || parse.Body == nil {
		return nil, fmt.Errorf("expected yySymType.span of type %s.Span and yyParserImpl.Parse", qualifier)
	}
	patch := fmt.Sprintf(spanPatch, qualifier)
	body := string(input[fset.Position(parse.Body.Pos()).Offset:fset.Position(parse.Body.End()).Offset])
	alreadyPatched := strings.Count(string(input), patch) == 1 && strings.Count(body, patch) == 1
	if alreadyPatched {
		body = strings.Replace(body, patch, "", 1)
	}
	if strings.Contains(strings.Replace(string(input), patch, "", 1), "parserkit/yaccspan:") {
		return nil, fmt.Errorf("unexpected or modified yaccspan patch")
	}
	if strings.Count(body, reduction) != 1 {
		return nil, fmt.Errorf("goyacc v0.52.0 reduction skeleton mismatch")
	}
	patchedReduction := strings.Replace(reduction, "\tyyVAL = yyS[yyp+1]\n", "\tyyVAL = yyS[yyp+1]\n"+patch, 1)
	if alreadyPatched {
		originalBody := string(input[fset.Position(parse.Body.Pos()).Offset:fset.Position(parse.Body.End()).Offset])
		if !strings.Contains(originalBody, patchedReduction) {
			return nil, fmt.Errorf("yaccspan patch is not at the reduction boundary")
		}
		return input, nil
	}
	start := fset.Position(parse.Body.Pos()).Offset + strings.Index(body, reduction)
	output := make([]byte, 0, len(input)+len(patch))
	output = append(output, input[:start]...)
	output = append(output, patchedReduction...)
	output = append(output, input[start+len(reduction):]...)
	return output, nil
}

func run(args []string) error {
	if len(args) != 1 {
		return fmt.Errorf("usage: yaccspan parser.go")
	}
	path := args[0]
	info, err := os.Lstat(path)
	if err != nil {
		return fmt.Errorf("stat parser: %w", err)
	}
	if !info.Mode().IsRegular() {
		return fmt.Errorf("parser must be a regular file, not a symlink or directory")
	}
	input, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read parser: %w", err)
	}
	output, err := rewrite(input)
	if err != nil {
		return err
	}
	if bytes.Equal(input, output) {
		return nil
	}
	// Replace atomically so a failed write cannot truncate the generated parser.
	f, err := os.CreateTemp(filepath.Dir(path), ".yaccspan-*")
	if err != nil {
		return fmt.Errorf("create patched parser: %w", err)
	}
	defer func() {
		_ = f.Close()
		_ = os.Remove(f.Name())
	}()
	if err := f.Chmod(info.Mode().Perm()); err != nil {
		return fmt.Errorf("preserve parser permissions: %w", err)
	}
	if _, err := f.Write(output); err != nil {
		return fmt.Errorf("write patched parser: %w", err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("close patched parser: %w", err)
	}
	if err := os.Rename(f.Name(), path); err != nil {
		return fmt.Errorf("replace parser: %w", err)
	}
	return nil
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "yaccspan:", err)
		os.Exit(1)
	}
}
