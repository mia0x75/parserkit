func fixture() []byte {
	return []byte(`// Code generated by goyacc -l -o parser.go parser.y. DO NOT EDIT.
package testparser
import "github.com/mia0x75/parserkit/loc"
type yySymType struct { yys int; span loc.Span }
type yyParserImpl struct{}
func (yyrcvr *yyParserImpl) Parse(yylex yyLexer) int {
` + reduction + `	case 1:
		yyVAL.node = newNode(yyVAL.span)
	}
	return 0
}
var yyR2 = [...]int{0, 0, 3}
const IDENT = 57346
`)
}

func TestRewrite(t *testing.T) {
	t.Parallel()
	input := fixture()
	output, err := rewrite(input)
	if err != nil {
		t.Fatal(err)
	}
	patch := []byte(fmtPatch("loc"))
	if bytes.Count(output, patch) != 1 || !bytes.Equal(bytes.Replace(output, patch, nil, 1), input) {
		t.Fatal("postprocessing must only insert one exact span block")
	}
	repeated, err := rewrite(output)
	if err != nil || !bytes.Equal(output, repeated) {
		t.Fatalf("postprocessing must be idempotent: %v", err)
	}
	aliased := bytes.ReplaceAll(input, []byte("loc.Span"), []byte("src.Span"))
	aliased = bytes.Replace(aliased, []byte(`import "github.com`), []byte(`import src "github.com`), 1)
	aliasedOutput, err := rewrite(aliased)
	if err != nil || !bytes.Contains(aliasedOutput, []byte(fmtPatch("src"))) {
		t.Fatalf("named source import was not honored: %v", err)
	}
}

func fmtPatch(qualifier string) string {
	return strings.ReplaceAll(spanPatch, "%[1]s", qualifier)
}

func TestRejectUnexpectedSource(t *testing.T) {
	t.Parallel()
	valid := string(fixture())
	patched, err := rewrite(fixture())
	if err != nil {
		t.Fatal(err)
	}
	tests := []struct {
		name  string
		input string
	}{
		{name: "not generated", input: strings.Replace(valid, "Code generated", "Hand written", 1)},
		{name: "broken Go", input: valid + "{"},
		{name: "missing import", input: strings.Replace(valid, "parserkit/loc", "elsewhere/loc", 1)},
		{name: "dot import", input: strings.Replace(valid, "import ", "import . ", 1)},
		{name: "blank import", input: strings.Replace(valid, "import ", "import _ ", 1)},
		{name: "wrong field", input: strings.Replace(valid, "span loc.Span", "span int", 1)},
		{name: "wrong receiver", input: strings.Replace(valid, "*yyParserImpl)", "*otherParser)", 1)},
		{name: "changed skeleton", input: strings.Replace(valid, "yyp -= int(yyR2[yyn])", "yyp -= 1", 1)},
		{name: "duplicate skeleton", input: strings.Replace(valid, reduction, reduction+"}\n"+reduction, 1)},
		{name: "modified patch", input: strings.Replace(string(patched), "yyi <= yypt", "yyi < yypt", 1)},
		{name: "duplicate patch", input: strings.Replace(string(patched), fmtPatch("loc"), fmtPatch("loc")+fmtPatch("loc"), 1)},
		{name: "misplaced patch", input: strings.Replace(strings.Replace(string(patched), fmtPatch("loc"), "", 1), "\treturn 0", fmtPatch("loc")+"\treturn 0", 1)},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if output, err := rewrite([]byte(tt.input)); err == nil || output != nil {
				t.Fatal("unexpected source must fail closed without output")
			}
		})
	}
}

func TestRun(t *testing.T) {
	t.Parallel()
	if err := run(nil); err == nil {
		t.Fatal("missing argument must fail")
	}
	dir := t.TempDir()
	path := filepath.Join(dir, "parser.go")
	input := fixture()
	if err := os.WriteFile(path, input, 0o640); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{path}); err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(path)
	if err != nil || info.Mode().Perm() != 0o640 {
		t.Fatalf("file permissions changed: %v", err)
	}
	output, err := os.ReadFile(path)
	if err != nil || bytes.Equal(input, output) {
		t.Fatalf("parser was not patched: %v", err)
	}
	if err := run([]string{path}); err != nil {
		t.Fatal(err)
	}
	broken := []byte("not Go")
	if err := os.WriteFile(path, broken, 0o640); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{path}); err == nil {
		t.Fatal("invalid input must fail")
	}
	unchanged, err := os.ReadFile(path)
	if err != nil || !bytes.Equal(unchanged, broken) {
		t.Fatalf("failed patch changed input: %v", err)
	}
	link := filepath.Join(dir, "link.go")
	if err := os.Symlink(path, link); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{link}); err == nil {
		t.Fatal("symlink must not be replaced")
	}
	if err := run([]string{dir}); err == nil {
		t.Fatal("directory must not be replaced")
	}
	entries, err := os.ReadDir(dir)
	if err != nil || len(entries) != 2 {
		t.Fatalf("temporary output was not cleaned up: %v", err)
	}
}

func TestGeneratedReduction(t *testing.T) {
	t.Parallel()
	input, err := os.ReadFile("testdata/reduction.go.txt")
	if err != nil {
		t.Fatal(err)
	}
	output, err := rewrite(input)
	if err != nil {
		t.Fatal(err)
	}
	tests, err := os.ReadFile("testdata/reduction_test.go.txt")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	parserPath := filepath.Join(dir, "parser.go")
	testPath := filepath.Join(dir, "parser_test.go")
	if err := os.WriteFile(parserPath, output, 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(testPath, tests, 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.CommandContext(t.Context(), "go", "test", "-count=1", parserPath, testPath)
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOPROXY=off")
	if output, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("compiled reduction test failed: %v\n%s", err, output)
	}
}
